/** Regions drawn as ocean/sea overlays instead of country fills. */
export const WATER_REGIONS = new Set([
  'atlantic-ocean',
  'pacific-ocean',
  'indian-ocean',
  'southern-ocean',
  'mediterranean-sea',
  'caribbean-sea',
  'gulf-of-mexico',
])

const countryToRegion = new Map<string, string>()
for (const [regionId, countries] of Object.entries(REGION_COUNTRIES)) {
  for (const country of countries) {
    countryToRegion.set(country, regionId)
  }
}

export function getRegionForCountry(countryName: string): string | undefined {
  return countryToRegion.get(countryName)
}

export function isCountryInRegion(countryName: string, regionId: string): boolean {
  return countryToRegion.get(countryName) === regionId
}
